from browser_helpers import URL, PASSWORD, ARTIFACTS, rendered
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1440, "height": 900})
    page.goto(URL)
    page.get_by_label("Username", exact=True).fill("admin")
    page.get_by_label("Password", exact=True).fill(PASSWORD)
    page.get_by_role("button", name="Sign in", exact=True).click()
    expect(page.get_by_role("link", name="Administration", exact=True)).to_be_visible()
    response = page.request.post(URL + "/api/instances", data={"game": "desktop"})
    assert response.ok, response.text()
    sid = response.json()["id"]
    try:
        page.goto(URL + "/play/" + sid)
        rendered(page)
        expect(page.locator("#viewer-scale")).to_be_hidden()
        expect(page.locator("#stop-instance")).to_be_visible()
        expect(page.locator("#previous")).to_be_hidden()
        page.screenshot(path=str(ARTIFACTS / "toolbar-clean.png"))
        page.locator("#player-settings-toggle").click()
        expect(page.locator("#player-settings")).to_be_visible()
        page.locator("#viewer-scale").select_option("original")
        expect(page.locator("#player-settings")).to_be_visible()
        page.screenshot(path=str(ARTIFACTS / "toolbar-settings.png"))
        page.keyboard.press("Escape")
        expect(page.locator("#player-settings")).to_be_hidden()
        page.locator("#player-settings-toggle").click()
        page.locator("#diagnostics-toggle").click()
        expect(page.locator("#player-settings")).to_be_hidden()
        expect(page.locator("#streaming-diagnostics")).to_be_visible()
        page.locator("#diagnostics-close").click()
        page.set_viewport_size({"width": 390, "height": 844})
        expect(page.locator("#stop-instance")).to_be_visible()
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
        page.locator("#player-settings-toggle").click()
        expect(page.locator("#viewer-scale")).to_be_visible()
        page.screenshot(path=str(ARTIFACTS / "toolbar-mobile.png"))
        page.locator("#player-settings-close").click()
        expect(page.locator("#player-settings")).to_be_hidden()
        print("PASS: clean toolbar, settings, scaling, Escape, diagnostics and mobile")
    finally:
        page.request.delete(URL + "/api/instances/" + sid, data={})
        browser.close()
